#!/usr/bin/env bash
# Wire this clone's tracked hooks. Idempotent. Run once after cloning, from a
# normal shell (an agent sandbox cannot write .git/config or .git/hooks), and
# again after moving or renaming the clone.
#
# Shims in the clone's own hooks directory exec the tracked hooks under
# .githooks/ and refuse when a tracked hook is missing, so a commit that
# deletes .githooks/ (the repo-wipe signature) is still blocked.
#
# core.hooksPath is set only when a global or system hooks path would
# otherwise override this clone; git's default hooks directory is resolved at
# run time, so it survives a rename and works in linked worktrees. When set,
# it is absolute and must be refreshed after a move.
#
# Verify any time:  just setup   (prints the resolved hooks directory)
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo"
hooks=(pre-commit pre-merge-commit pre-push)

common="$(git rev-parse --git-common-dir)"
[[ "$common" = /* ]] || common="$repo/$common"
shimdir="$common/hooks"
mkdir -p "$shimdir"

for h in "${hooks[@]}"; do
  target="$h"
  [[ "$h" = pre-merge-commit ]] && target=pre-commit
  # shellcheck disable=SC2016  # the shim must contain literal $hook and $@
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Generated by scripts/setup-hooks.sh. Refuses when the tracked hook is missing.' \
    "hook=\"\$(git rev-parse --show-toplevel)/.githooks/$target\"" \
    'if [ ! -x "$hook" ]; then echo "[hooks] tracked hook missing: $hook (refusing)" >&2; exit 1; fi' \
    'exec "$hook" "$@"' \
    > "$shimdir/$h"
  chmod +x "$shimdir/$h"
done
chmod +x .githooks/pre-commit .githooks/pre-push

git config --unset core.hooksPath 2>/dev/null || true
outer="$(git config --get core.hooksPath 2>/dev/null || true)"
if [[ -n "$outer" ]]; then
  git config core.hooksPath "$shimdir"
  echo "[setup-hooks] outer hooksPath '$outer' overridden for this clone; re-run after moving it."
fi
resolved="$(git config --get core.hooksPath 2>/dev/null || echo "$shimdir")"
[[ "$resolved" -ef "$shimdir" && -x "$resolved/pre-commit" ]] || { echo "[setup-hooks] ERROR: hooks resolve to '${resolved:-<unset>}', not $shimdir" >&2; exit 1; }

command -v gitleaks >/dev/null || echo "[setup-hooks] WARN: gitleaks is not installed; commits will be refused until it is." >&2
command -v just >/dev/null || echo "[setup-hooks] WARN: just is not installed; commits will be refused until it is." >&2
echo "[setup-hooks] hooks directory: $resolved"
